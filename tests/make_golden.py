"""Generate a game's golden-value TOML from its raw files.

    uv run python tests/make_golden.py test_games/sq1 > tests/games/sq1.toml

Deliberately independent of resource/ and util/: golden values made by the
decoders under test would only check them against themselves.
"""
import sys
from pathlib import Path

OBJECT_KEY = b"Avis Durgan"
DIR_NAMES = ["VIEWDIR", "LOGDIR", "PICDIR", "SNDDIR"]
MAX_SLOTS = 256
PER_LINE = 6


def decode_objects(raw: bytes) -> tuple[int, list[str], list[int]]:
    d = bytes(b ^ OBJECT_KEY[i % len(OBJECT_KEY)] for i, b in enumerate(raw))
    names_start = d[0] | d[1] << 8
    entries = [d[3 + i:6 + i] for i in range(0, names_start, 3)]
    names = [d[p:d.index(0, p)].decode("ascii") for p in ((e[0] | e[1] << 8) + 3 for e in entries)]
    return d[2], names, [e[2] for e in entries]


def decode_dir(raw: bytes) -> list[tuple[int, int]]:
    triplets = [raw[i:i + 3] for i in range(0, min(len(raw) // 3, MAX_SLOTS) * 3, 3)]
    return [(t[0] >> 4, (t[0] & 0xF) << 16 | t[1] << 8 | t[2]) for t in triplets]


def repr_toml(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def toml_list(items: list[str], indent: str = "    ") -> str:
    lines = [", ".join(items[i:i + PER_LINE]) for i in range(0, len(items), PER_LINE)]
    return "[\n" + "".join(f"{indent}{line},\n" for line in lines) + "]"


def render(game_dir: Path) -> str:
    max_animated, names, rooms = decode_objects((game_dir / "OBJECT").read_bytes())
    out = [
        f"# Generated by tests/make_golden.py from {game_dir.as_posix()}; do not edit by hand.",
        "",
        "[objects]",
        f"max_animated = {max_animated}",
        f"names = {toml_list([repr_toml(n) for n in names])}",
        f"rooms = {toml_list([str(r) for r in rooms])}",
    ]
    for name in DIR_NAMES:
        entries = decode_dir((game_dir / name).read_bytes())
        out += ["", f"[dirs.{name}]", "# [vol, offset] per slot; vol 15 marks an absent slot.",
                f"entries = {toml_list([f'[{v}, {o}]' for v, o in entries])}"]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render(Path(sys.argv[1])))
